#!/usr/bin/env node
'use strict';
// OzarLand Production Guide: build.
//
//   node scripts/build.cjs                 validate, render every memo to dist/, regenerate pages and catalog
//   node scripts/build.cjs --only <slug>   render one memo (pages and catalog are still regenerated)
//   node scripts/build.cjs --validate      validate content and runbook links only, render nothing
//   node scripts/build.cjs --scale 2       export at 2160 x 2700 instead of 1080 x 1350
//   node scripts/build.cjs --runbooks DIR  check the runbook references against DIR (default: ../runbooks)
//   node scripts/build.cjs --offline       skip the runbook check when the runbooks are not available
//
// Sources: categories/<category>/<slug>.yml (content), templates/ (presentation).
// Outputs: dist/*.png, categories/<category>/<slug>.md, index.md catalog, LINKEDIN.md.
// This module is docs/production/ of OzarLand Academy; the runbooks are the module docs/runbooks/.

const fs = require('fs');
const path = require('path');
const { ROOT, loadMemos, validateMemo, validateCollection, fileBase } = require('./lib/content.cjs');
const { REPO, BLOB, runbookLink, findCheckout, checkRunbooks } = require('./lib/runbooks.cjs');
const { renderMemo, plain, CATEGORIES, CAUTION } = require('../templates/memo.cjs');

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n) => (args.includes(n) ? args[args.indexOf(n) + 1] : undefined);

// Font hinting depends on the machine's FreeType and fontconfig settings and changes glyph advances by a fraction
// of a pixel, enough to wrap a line differently on another machine. Turning it off makes the layout the same
// everywhere, which is what lets CI re-render the collection and agree with a local build.
const LAUNCH = { args: ['--font-render-hinting=none'] };
const DIST = path.join(ROOT, 'dist');
const HTML = path.join(ROOT, '.cache', 'html');
const GUIDE = `${REPO}/tree/main/docs/production`;
const ISSUES = `${REPO}/issues/new`;
const GENERATED = (src) => `<!-- Generated by scripts/build.cjs from ${src}. Do not edit: change the source and rebuild. -->`;

function fail(errors) {
  console.error(`\n${errors.length} problem(s):\n` + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

// ---------- Generated Markdown ----------

const mdText = (s) => String(s).replace(/\*\*([^*]+)\*\*/g, '$1');

// Front matter of a generated page: the title and description of the page in the portal. JSON strings are valid
// YAML double-quoted scalars.
const frontMatter = (title, description) =>
  ['---', `title: ${JSON.stringify(plain(title))}`, `description: ${JSON.stringify(plain(description))}`, '---', ''].join('\n');

function memoPage(m) {
  const img = `../../dist/${fileBase(m)}.png`;
  const rbs = m._runbooks && m._runbooks.length ? m._runbooks : [{ path: m.runbook.path, url: BLOB + m.runbook.path }];
  const here = `categories/${m.category}`;
  const li = m.linkedin;
  const tags = li.hashtags.map((t) => `#${t}`).join(' ');
  const out = [
    frontMatter(`${m.id} · ${m.title}`, m.lesson),
    `[← Production Guide](../../index.md#catalog) · ${CATEGORIES[m.category]}`,
    '',
    GENERATED(`${m._slug}.yml`),
    '',
    `# ${m.id} · ${mdText(m.title)}`,
    '',
    `<img src="${img}" alt="${plain(m.title)} Operational lesson: ${plain(m.lesson)}" width="540">`,
    '',
    `> **Operational lesson.** ${mdText(m.lesson)}`,
    '',
    '## The memo as text',
    '',
    `**Situation.** ${mdText(m.situation)}`,
    '',
    '**First checks** (read-only):',
    '',
    ...m.checks.map((c, i) => `${i + 1}. **${mdText(c.label)}**${c.hint ? `: \`${c.hint}\`` : ''}`),
    '',
    '**Think before acting:**',
    '',
    ...m.caution.map((c) => `- ${c.level === 'destructive' ? '🛑' : c.level === 'state-changing' ? '⚠️' : c.level === 'avoid' ? '⛔' : 'ℹ️'} **${CAUTION[c.level].tag}** ${mdText(c.text)}`),
    '',
    '## Go deeper',
    '',
    'This memo is a memory aid. The procedure, with every command, its risk warning and its limits, is in the runbook:',
    '',
    ...rbs.map((r) => `- [${r.title || r.path}](${runbookLink(r.path, here)})${r.status ? ` · \`${r.status}\`${r.releases && r.releases.length ? ` on ${r.releases.join(', ')}` : ''}${r.risk ? ` · highest risk in the page: ${r.risk}` : ''}` : ''}`),
    '',
    `**Where this holds.** ${mdText(m.scope)}`,
    '',
    '## LinkedIn kit',
    '',
    `- **Image:** [\`dist/${fileBase(m)}.png\`](${img}) (1080 × 1350)`,
    `- **Post title:** ${li.title}`,
    '',
    '```text',
    li.caption.trim(),
    '',
    `Runbook: ${rbs[0].url}`,
    `More memos: ${GUIDE}`,
    '',
    tags,
    '```',
    '',
    '---',
    '',
    `*Source: [\`${m._slug}.yml\`](${m._slug}.yml). Found an error, or does your platform behave differently? [Open an issue](${ISSUES}) or see [CONTRIBUTING](../../CONTRIBUTING.md).*`,
    '',
  ];
  return out.join('\n');
}

function catalog(memos) {
  const out = [];
  for (const [cat, name] of Object.entries(CATEGORIES)) {
    const list = memos.filter((m) => m.category === cat);
    if (!list.length) continue;
    out.push(`### ${name}`, '', '| | Memo | Operational lesson | Runbook |', '|---|---|---|---|');
    for (const m of list) {
      const page = `categories/${cat}/${m._slug}.md`;
      out.push(
        `| <a href="${page}"><img src="dist/${fileBase(m)}.png" alt="${plain(m.title)}" width="150"></a> ` +
          `| **${m.id}**<br>[${mdText(m.title)}](${page}) ` +
          `| ${mdText(m.lesson)} ` +
          `| [${m.runbook.path.split('/')[0]}/…](${runbookLink(m.runbook.path, '')})<br>\`${m.runbook.status}\` |`
      );
    }
    out.push('');
  }
  return out.join('\n');
}

// Runbooks that no memo is written from or cites: the next memos to write.
function candidates(memos, dir) {
  const used = new Set(memos.flatMap((m) => [m.runbook.path, ...(m.runbook.also || [])]));
  const rows = [];
  for (const folder of fs.readdirSync(dir).sort()) {
    const d = path.join(dir, folder);
    if (folder.startsWith('.') || ['logs', 'templates'].includes(folder) || !fs.statSync(d).isDirectory()) continue;
    for (const f of fs.readdirSync(d).sort()) {
      const p = `${folder}/${f}`;
      if (!f.endsWith('.md') || f === 'index.md' || used.has(p)) continue;
      const t = fs.readFileSync(path.join(d, f), 'utf8');
      const title = (/^title:\s*(.+)$/m.exec(t) || [, p])[1].replace(/^["']|["']$/g, '').replace(/\|/g, '/');
      const status = (/^status:\s*(\S+)/m.exec(t) || [, '?'])[1];
      rows.push(`| [${title}](${runbookLink(p, '')}) | \`${status}\` |`);
    }
  }
  return rows.length ? ['| Runbook | Status |', '|---|---|', ...rows].join('\n') : 'None at the moment: every runbook has its memo.';
}

