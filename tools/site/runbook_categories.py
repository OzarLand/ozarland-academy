#!/usr/bin/env python3
"""Write the index page of each category of the VM runbooks site.

The home page of the runbooks (docs/runbooks/index.md) holds the catalogue:
one folded table per category under "## Index", and the table of folders
under "How content is organised". Without an index page of its own, the tab
and the breadcrumb item of a category open its first runbook. This script
writes docs/runbooks/<category>/index.md from the home page, so a category
lists its runbooks and stays in step with the catalogue.

    python3 tools/site/runbook_categories.py           # write the pages
    python3 tools/site/runbook_categories.py --check   # fail if one is stale

A category that has its own hand-written index page (logs/) is left alone.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "runbooks"
MARK = "<!-- Generated by tools/site/runbook_categories.py from index.md: do not edit. -->"

SUMMARY = re.compile(r"<summary><b>(?P<emoji>\S+) (?P<title>[^<]+)</b></summary>")
FOLDER = re.compile(r"^\| (?P<emoji>\S+) `(?P<folder>[a-z-]+)/` \| (?P<scope>.+) \|$", re.MULTILINE)
LINK = re.compile(r"\]\((?P<folder>[a-z-]+)/(?P<page>[^)#]+)\)")


def categories(home: str) -> list[dict[str, str]]:
    scopes = {m["folder"]: m["scope"] for m in FOLDER.finditer(home)}
    index = home.split("\n## Index", 1)[1].split("\n## ", 1)[0]
    found = []
    for block in index.split("<details markdown>")[1:]:
        block = block.split("</details>", 1)[0]
        head = SUMMARY.search(block)
        rows = [line for line in block.splitlines() if line.startswith("|")]
        folders = {m["folder"] for m in LINK.finditer("\n".join(rows[2:]))}
        if not head or len(folders) != 1:
            sys.exit(f"runbook_categories: cannot read the category {head and head['title']!r} of index.md")
        folder = folders.pop()
        table = "\n".join(LINK.sub(lambda m: f"]({m['page']})", row) for row in rows)
        found.append({"folder": folder, "emoji": head["emoji"], "title": head["title"],
                      "scope": scopes.get(folder, ""), "table": table, "count": str(len(rows) - 2)})
    return found


def page(cat: dict[str, str]) -> str:
    scope = re.sub(r"\]\([a-z-]+/", "](", cat["scope"])
    scope = scope.replace("](logs/index.md)", "](index.md)")
    count = cat["count"]
    return f"""---
title: "{cat['title']} runbooks"
description: "{cat['title']} runbooks for OpenStack instances and hypervisors: {scope.split(' (')[0].lower()}."
---

{MARK}

# {cat['emoji']} {cat['title']}

{scope}. {count} runbook{'s' if count != '1' else ''} in this category: open the one that matches what you
see. Not sure which category? [Start from what you see](../index.md#-start-from-what-you-see) or browse the
[index of every category](../index.md#index). The statuses are explained in
[How much each page was checked](../index.md#-how-much-each-page-was-checked).

{cat['table']}
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a page differs from what index.md gives")
    args = parser.parse_args(argv)
    stale = []
    for cat in categories((DOCS / "index.md").read_text(encoding="utf-8")):
        target = DOCS / cat["folder"] / "index.md"
        if target.exists() and MARK not in target.read_text(encoding="utf-8"):
            continue
        text = page(cat)
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(text, encoding="utf-8")
            print(f"runbook_categories: wrote {target.relative_to(ROOT)}")
    if stale:
        print("runbook_categories: stale, run python3 tools/site/runbook_categories.py:\n  " + "\n  ".join(stale))
        return 1
    print("runbook_categories: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
