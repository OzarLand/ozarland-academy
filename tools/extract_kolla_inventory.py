#!/usr/bin/env python3
"""Extract play / tag / service / handler tables from a Kolla-Ansible checkout.

Usage: extract_kolla_inventory.py [--release <id>] <kolla-ansible checkout> [output.md]

Default output: docs/day2/<id>/reference/generated-inventory.md, where <id> is the
release given with --release, or the default release of academy.toml. The
checkout must be at the tag of that release. If the output file starts
with a front matter block (--- ... ---), that block is kept and only the body is
rewritten.

Pure static analysis (PyYAML only). Written for the ussuri-eol tree; every
table row carries the file it came from so it can be checked by hand.
"""
import glob
import os
import re
import sys

import yaml

def release_argument(argv):
    """Take `--release <id>` (or `--release=<id>`) out of the arguments.

    Returns (docs directory of the release, remaining arguments). Without the
    option the release is the default one of the day-2 module (academy.toml).
    """
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, os.path.join(here, 'site'))
    import releases
    rest, release = [], None
    args = iter(argv)
    for arg in args:
        if arg == '--release':
            release = next(args, None)
            if release is None:
                sys.exit('--release needs the id of a release')
        elif arg.startswith('--release='):
            release = arg.split('=', 1)[1]
        else:
            rest.append(arg)
    root = os.path.dirname(here)
    try:
        registry = releases.load_registry(releases.Path(root))
        release = releases.select(registry, release or registry.default)[0]
    except releases.RegistryError as error:
        sys.exit('academy.toml: ' + '; '.join(error.problems))
    return os.path.join(root, *release.docs_dir.split('/')), rest


DOCS, ARGS = release_argument(sys.argv[1:])
SRC = ARGS[0]
OUT = ARGS[1] if len(ARGS) > 1 else os.path.join(DOCS, 'reference', 'generated-inventory.md')
A = os.path.join(SRC, 'ansible')


def load(p):
    with open(p) as f:
        return yaml.safe_load(f)


def short(v, n=70):
    s = ' '.join(str(v).split())
    return s if len(s) <= n else s[:n - 1] + '…'


def esc(s):
    return str(s).replace('|', '\\|')


out = []
w = out.append

# ---------------------------------------------------------------- plays
def plays_of(pb, origin):
    rows = []
    for play in load(os.path.join(A, pb)) or []:
        if 'import_playbook' in play:
            rows += plays_of(play['import_playbook'], play['import_playbook'])
            continue
        hosts = play.get('hosts')
        hosts = hosts if isinstance(hosts, list) else [hosts]
        ptags = play.get('tags', [])
        ptags = ptags if isinstance(ptags, list) else [ptags]
        roles, rtags = [], []
        for r in play.get('roles', []) or []:
            if isinstance(r, dict):
                roles.append(r.get('role'))
                t = r.get('tags', [])
                rtags += t if isinstance(t, list) else [t]
            else:
                roles.append(r)
        tasks = []
        for t in play.get('tasks', []) or []:
            for k in ('include_role', 'import_role'):
                if k in t:
                    tasks.append('%s:%s/%s' % (k, t[k].get('name'), t[k].get('tasks_from', 'main')))
            if 'block' in t:
                tasks.append('block(%d include_role loadbalancer)' % len(t['block']))
        rows.append(dict(origin=origin, name=play.get('name'), hosts=hosts, ptags=ptags,
                         rtags=rtags, serial=play.get('serial'), roles=roles, tasks=tasks,
                         any_errors_fatal=play.get('any_errors_fatal')))
    return rows

plays = plays_of('site.yml', 'site.yml')
w('# Generated inventory\n')
w('Source: `%s` — generated by `tools/extract_kolla_inventory.py`. Do not edit by hand.\n' % os.path.basename(SRC.rstrip('/')))
w('## 1. Plays executed by `site.yml` (in order)\n')
w('`serial` column: `kolla_serial` means `serial: \'{{ kolla_serial|default("0") }}\'`; empty means no serial key (all hosts in one batch).\n')
w('| # | Origin | Play | Host patterns | Play tags | Role tags | serial | Roles / tasks |')
w('|---|---|---|---|---|---|---|---|')
for i, p in enumerate(plays, 1):
    serial = p['serial'] or ''
    if 'kolla_serial' in str(serial):
        serial = 'kolla_serial'
    elif serial:
        serial = '`%s`' % serial
    w('| %d | %s | %s | %s | %s | %s | %s | %s |' % (
        i, p['origin'], esc(p['name']), esc(', '.join(map(str, p['hosts']))),
        ', '.join(p['ptags']), ', '.join(sorted(set(p['rtags']))), serial,
        esc(', '.join([r for r in p['roles'] if r] + p['tasks']))))

# ---------------------------------------------------------------- services
w('\n## 2. Containers defined by each role (`<role>_services` in `defaults/main.yml`)\n')
w('`placement` column: `group:` = static inventory group; `host_in_groups:` = per-host boolean expression (takes precedence, see `kolla_ansible/filters.py`).\n')
w('| Role | Service key | Container | Placement | Enabled when | privileged | pid/ipc | HAProxy entries |')
w('|---|---|---|---|---|---|---|---|')
svc_count = 0
for d in sorted(glob.glob(os.path.join(A, 'roles', '*', 'defaults', 'main.yml'))):
    role = d.split(os.sep)[-3]
    try:
        data = load(d) or {}
    except Exception as e:  # pragma: no cover
        continue
    for k, v in data.items():
        if not (k.endswith('_services') and isinstance(v, dict)):
            continue
        for sk, s in v.items():
            if not isinstance(s, dict) or 'container_name' not in s:
                continue
            svc_count += 1
            if s.get('host_in_groups') is not None:
                pl = 'host_in_groups: ' + short(s['host_in_groups'], 60)
            else:
                pl = 'group: ' + str(s.get('group'))
            mode = '/'.join(x for x in (s.get('pid_mode') and 'pid=' + s['pid_mode'],
                                         s.get('ipc_mode') and 'ipc=' + s['ipc_mode']) if x)
            ha = ', '.join(sorted((s.get('haproxy') or {}).keys()))
            w('| %s | %s | `%s` | %s | %s | %s | %s | %s |' % (
                role, sk, s['container_name'], esc(pl), esc(short(s.get('enabled'), 50)),
                'yes' if s.get('privileged') in (True, 'True', 'yes') else '', mode, esc(ha)))
w('\nTotal container definitions: %d\n' % svc_count)

# ---------------------------------------------------------------- per role tasks
KEYS = {'name', 'when', 'become', 'vars', 'with_items', 'with_dict', 'loop', 'loop_control',
        'register', 'notify', 'tags', 'run_once', 'delegate_to', 'until', 'retries', 'delay',
        'changed_when', 'failed_when', 'ignore_errors', 'no_log', 'with_subelements',
        'with_first_found', 'with_together', 'with_sequence', 'listen', 'block', 'rescue',
        'always', 'any_errors_fatal', 'delegate_facts', 'become_user', 'environment',
        'with_nested', 'with_fileglob', 'args', 'check_mode', 'local_action', 'connection',
        'throttle', 'with_indexed_items'}


def walk(tasks, acc):
    if not isinstance(tasks, list):
        return
    for t in tasks:
        if not isinstance(t, dict):
            continue
        for k in ('block', 'rescue', 'always'):
            if k in t:
                walk(t[k], acc)
        mods = [k for k in t if k not in KEYS]
        acc.append((t, mods[0] if mods else None))


w('## 3. Role task structure, handlers and helper-role usage\n')
w('Columns: **reconf→deploy** = `tasks/reconfigure.yml` only imports `deploy.yml` (\"yes (include)\" when it only includes it dynamically); **bootstrap in deploy** = `deploy.yml` imports/includes `bootstrap*.yml`; **ks-register / rabbitmq** = imports `service-ks-register` / `service-rabbitmq`; **run_once** = number of tasks with `run_once`; **handlers** = handler names.\n')
w('| Role | task files | reconf→deploy | bootstrap in deploy | ks-register | rabbitmq | merge_configs | run_once | Handlers |')
w('|---|---|---|---|---|---|---|---|---|')
for rd in sorted(glob.glob(os.path.join(A, 'roles', '*'))):
    role = os.path.basename(rd)
    tfiles = sorted(os.path.basename(f) for f in glob.glob(os.path.join(rd, 'tasks', '*.yml')))
    if not tfiles:
        continue
    def read(f):
        p = os.path.join(rd, 'tasks', f)
        return open(p).read() if os.path.exists(p) else ''
    reconf = read('reconfigure.yml')
    m = re.search(r'(import|include)_tasks:\s*["\']?deploy\.yml', reconf)
    n_inc = len(re.findall(r'(import|include)_tasks:', reconf))
    reconf_deploy = ('-' if not reconf else
                     'yes' if m and n_inc == 1 and m.group(1) == 'import' else
                     'yes (include)' if m and n_inc == 1 else 'no')
    dep = read('deploy.yml')
    boot = 'yes' if re.search(r'(import|include)_tasks:\s*bootstrap', dep) else ''
    alltxt = ''.join(read(f) for f in tfiles)
    ks = 'yes' if 'service-ks-register' in alltxt else ''
    rmq = 'yes' if 'service-rabbitmq' in alltxt else ''
    mc = alltxt.count('merge_configs:')
    ro = len(re.findall(r'run_once:\s*(True|true|yes)', alltxt))
    hfile = os.path.join(rd, 'handlers', 'main.yml')
    hn = []
    if os.path.exists(hfile):
        for h in load(hfile) or []:
            hn.append(h.get('name'))
    w('| %s | %d | %s | %s | %s | %s | %d | %d | %s |' % (
        role, len(tfiles), reconf_deploy, boot, ks, rmq, mc, ro, esc('; '.join(map(str, hn)))))

# ---------------------------------------------------------------- templates looping over groups
w('\n## 4. Templates that reference inventory groups\n')
w('**Host list** = the template loops over the group (`for ... in groups[...]`), so the rendered file changes on '
  '**every host that renders it** when the group gains or loses a member. **Other reference** = membership test '
  '(`inventory_hostname in groups[...]`), first-member lookup (`groups[...][0]`) or length check; such a file changes '
  'only where the test result or the referenced member changes.\n')
w('| Template | Host list (loops) | Other reference |')
w('|---|---|---|')
pat = re.compile(r"groups\[['\"]?([A-Za-z0-9_\-]+)['\"]?\]")
loop_pat = re.compile(r"for\s+\w+\s+in\s+groups\[['\"]?([A-Za-z0-9_\-]+)['\"]?\]")
for t in sorted(glob.glob(os.path.join(A, 'roles', '*', 'templates', '**', '*.j2'), recursive=True)):
    txt = open(t).read()
    if 'groups[' not in txt:
        continue
    gs = set(pat.findall(txt))
    loops = set(loop_pat.findall(txt))
    other = set()
    for m in pat.finditer(txt):
        if not re.search(r"for\s+\w+\s+in\s+$", txt[max(0, m.start() - 40):m.start()]):
            other.add(m.group(1))
    if gs:
        w('| `%s` | %s | %s |' % (os.path.relpath(t, SRC), ', '.join(sorted(loops)), ', '.join(sorted(other))))
w('\nNote: in addition, `rpc_transport_url` / `notify_transport_url` (`ansible/group_vars/all.yml`) loop over `groups[om_rpc_group]` (= `rabbitmq`) and are rendered into every OpenStack service configuration that uses messaging.\n')

front = ''
if os.path.exists(OUT):
    m = re.match(r'---\n.*?\n---\n+', open(OUT, encoding='utf-8').read(), re.S)
    front = m.group(0) if m else ''
open(OUT, 'w', encoding='utf-8').write(front + '\n'.join(out).rstrip('\n') + '\n')
print('wrote', OUT, len(out), 'lines;', len(plays), 'plays;', svc_count, 'services')
